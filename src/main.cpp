// Для справки, вот как часто вызываются разные компоненты:
//
// loop()                      → 500 Hz (каждые 2ms)
// flightController.update()   → 500 Hz (каждые 2ms)
// receiver.update()           → 500 Hz (каждые 2ms)
// IBusReceiver парсит кадры   → 100 Hz (в среднем)
//   (кадры приходят каждые ~10ms от приёмника)
// mixer.calculate()           → 500 Hz (каждые 2ms)
// throttleManager.update()    → 500 Hz (каждые 2ms)
// outputs.update()            → 500 Hz (каждые 2ms)
//   (PWM сигналы на 50 Hz, но обновляются каждый цикл)
// debugLogger.update()        → 2 Hz (каждые 500ms)
//
// Это очень эффективно! Система готова к выполнению
// сотен дополнительных циклов если потребуется.
// ============================================================