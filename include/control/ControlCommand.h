#pragma once
#include <stdint.h>

// ============================================================
// CONTROL COMMAND
//
// Команда на рули в "физических" знаках, мкс отклонения
// (±500 = полный ход). Общий язык стиков, автопилота и микшера:
// ControlMixer::fromSticks() строит её из RC-каналов,
// FlightController прибавляет коррекции Autopilot (в тех же
// знаках), ControlMixer::mix() переводит в PWM каждого серво.
//
//   roll  > 0 — крен вправо   (правый элерон вверх, левый вниз)
//   pitch > 0 — нос вверх     (руль высоты вверх)
//   yaw   > 0 — нос вправо    (руль направления и колесо вправо)
//   flaps > 0 — закрылки вниз (оба элерона вниз)
// ============================================================

struct ControlCommand
{
    int16_t roll = 0;
    int16_t pitch = 0;
    int16_t yaw = 0;
    int16_t flaps = 0;
};
