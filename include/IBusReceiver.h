// ============================================================
// 📡 ПРИЁМНИК iBUS СИГНАЛОВ (IBusReceiver)
//
// НАЗНАЧЕНИЕ:
//   Получать RC команды через UART приёмник iBUS протокол
//   и преобразовывать их в 10 RC каналов (µs)
//
// ВХОДНЫЕ ДАННЫЕ:
//   UART (GPIO3, 115200 baud) → iBUS кадры от приёмника
//   Кадры приходят с частотой ~100 Hz (каждые ~10ms)
//
// ВЫХОДНЫЕ ДАННЫЕ:
//   RcChannelState → 10 каналов (CH1-CH10, каждый 1000-2000 µs)
//
// iBUS PROTOCOL:
//   Кадр формат:
//   [0x20] [0x40] [CH1-L] [CH1-H] ... [CH10-L] [CH10-H] [CRC-L] [CRC-H]
//
//   Каждый канал = 16-bit число (little-endian):
//   CH_value = LOW_byte | (HIGH_byte << 8)
//
//   Диапазон каналов: 1000–2000 µс (в микросекундах)
//   Nейтраль: ~1500 µs
//
// FAILSAFE:
//   Если нет кадра > 500ms → сигнал потерян
//   isSignalLost() возвращает true
//   FlightController переходит в режим failsafe
//
// ВАЖНО!
//   Этот класс ТОЛЬКО парсит UART и выдает каналы.
//   НЕ применяет никакую логику управления.
//   НЕ знает о failsafe режиме самолёта.
//   НЕ знает о сервоприводах.
//   НЕ знает о системе ARM/DISARM.
//
//   Если позже понадобится другой протокол (S-Bus, PWM):
//   - Заменяем ТОЛЬКО этот класс
//   - Остальной код не меняется!
//   - Это и есть преимущество хорошей архитектуры!
// ============================================================

class IBusReceiver
{
public:

    // ========================================================
    // КОНСТРУКТОР
    // ========================================================
    // Принимает ссылку на HardwareSerial объект (UART1)
    //
    // Пример в main.cpp:
    //   HardwareSerial IBusSerial(1);
    //   IBusReceiver ibusReceiver(IBusSerial);
    // ========================================================

    explicit IBusReceiver(HardwareSerial& serial)
        : serial(serial)
    {
    }


    // ========================================================
    // ИНИЦИАЛИЗАЦИЯ UART
    // ========================================================
    // Вызывается один раз при включении системы (в setup())
    //
    // Параметры:
    //   Baudrate:  115200 (стандарт для iBUS)
    //   Data bits: 8
    //   Parity:    None
    //   Stop bits: 1
    //   PIN:       GPIO3 (RX линия ESP32-C3)
    //   TX PIN:    -1 (не используется, только приём)
    //
    // После вызова:
    //   UART готов слушать iBUS кадры
    //   Таймер failsafe сбросьется
    // ========================================================

    void begin()
    {
        serial.begin(
            Config::IBUS_BAUDRATE,
            SERIAL_8N1,
            Config::PIN_IBUS,
            -1
        );

        lastFrameTime = micros();
    }


    // ========================================================
    // ОБНОВЛЕНИЕ СОСТОЯНИЯ
    // ========================================================
    // Вызывается каждый цикл из loop() (каждые 2ms)
    //
    // Логика:
    //   1. Читаем все доступные байты из UART буфера
    //   2. Парсим каждый байт (ищем iBUS кадр)
    //   3. Если полный кадр получен:
    //      • Проверяем checksum
    //      • Извлекаем 10 каналов (CH1-CH10)
    //      • Обновляем RcChannelState
    //      • Записываем время получения
    //   4. Если нет кадров > 500ms → failsafe!
    //
    // Частота обновления:
    //   Кадры приходят ~100 Hz (каждые ~10ms)
    //   update() вызывается 500 Hz (каждые 2ms)
    //   → В большинстве циклов нов кадров нет
    //   → Но часто появляются новые байты в UART буфере
    // ========================================================

    void update()
    {
        // Пока есть байты в UART буфере → читаем
        // (UART имеет буфер 256 байт, обычно переполнения нет)
        while (serial.available())
        {
            const uint8_t byte = serial.read();

            processByte(byte);
        }
    }


    // ========================================================
    // ПОЛУЧИТЬ СОСТОЯНИЕ КАНАЛОВ
    // ========================================================
    // Возвращает const ссылку на RcChannelState
    // (объект содержит 10 каналов: CH1-CH10)
    //
    // Пример использования:
    //   const RcChannelState& rc = ibusReceiver.getState();
    //   uint16_t aileron = rc.get(Channels::AILERON);
    //
    // Формат каналов:
    //   Каждый канал = 16-bit число (1000–2000 µs)
    //   CH1 (AILERON):  1000 = влево, 1500 = центр, 2000 = вправо
    //   CH2 (ELEVATOR): 1000 = вверх, 1500 = центр, 2000 = вниз
    //   CH3 (THROTTLE): 1000 = минимум, 2000 = максимум
    //   ... и т.д.
    // ========================================================

    const RcChannelState& getState() const
    {
        return state;
    }


    // ========================================================
    // ПРОВЕРКА ПОТЕРИ СИГНАЛА (FAILSAFE)
    // ========================================================
    // Возвращает true, если сигнал потерян
    //
    // Логика:
    //   Если прошло > 500ms без валидного iBUS кадра
    //   → возвращаем true (сигнал потерян)
    //   → FlightController вызывает failsafe режим
    //
    // Config::RX_TIMEOUT_US = 500000 микросекунд = 500 миллисекунд
    //
    // Почему 500ms?
    //   • Кадры приходят каждые ~10ms
    //   • 500ms = 50 отсутствующих кадров подряд
    //   • Это гарантирует, что сигнал действительно потерян
    //   • А не просто задержка в UART
    //
    // Пример использования:
    //   if (receiver.isSignalLost())
    //   {
    //       // Потеря сигнала! Переходим на failsafe
    //       outputs.setFailsafe();
    //   }
    // ========================================================

    bool isSignalLost() const
    {
        return (micros() - lastFrameTime) > Config::RX_TIMEOUT_US;
    }


    // ========================================================
    // ВРЕМЯ ПОСЛЕДНЕГО КАДРА
    // ========================================================
    // Возвращает micros() момента получения последнего
    // валидного iBUS кадра
    //
    // Используется для диагностики и отладки:
    //   - Проверить время последнего кадра
    //   - Вычислить время без сигнала
    //   - Логирование в отладку
    // ========================================================

    uint32_t getLastFrameTime() const
    {
        return lastFrameTime;
    }


private:

    // ========================================================
    // ПРИВАТНЫЕ ПЕРЕМЕННЫЕ
    // ========================================================

    HardwareSerial& serial;           // UART1 (GPIO3)

    RcChannelState state;             // 10 RC каналов (CH1-CH10)

    uint8_t frame[Config::IBUS_FRAME_LENGTH] = {};  // Буфер текущего кадра

    uint8_t frameIndex = 0;           // Позиция парсинга в кадре

    uint32_t lastFrameTime = 0;       // micros() последнего валидного кадра


    // ========================================================
    // ПАРСИНГ ОДНОГО БАЙТА
    // ========================================================
    // Внутренний метод для обработки входящих байтов
    //
    // Состояние парсера (frameIndex):
    //   0 → ждём первый байт: 0x20
    //   1 → ждём второй байт: 0x40
    //   2-31 → собираем остальные данные (30 байт)
    //
    // После получения 32 байтов вызываем processFrame()
    //
    // Почему не парсим сразу весь буфер?
    //   Потому что UART кадры могут приходить разбитыми
    //   на несколько порций. Байт за байтом будут
    //   попадать в serial.available() буфер.
    //   Парсим постепенно, байт за байтом.
    // ========================================================

    void processByte(uint8_t byte)
    {
        // ====================================================
        // ЭТАП 1: Ищем первый байт заголовка (0x20)
        // ====================================================
        // Если мы в начале парсинга (frameIndex == 0)
        // и байт не 0x20, то это не кадр iBUS
        // → Сбрасываем и ждём следующего байта
        // ====================================================

        if (frameIndex == 0)
        {
            if (byte != Config::IBUS_HEADER_0)
            {
                return;  // Ложный старт, ждём следующего
            }

            frame[frameIndex++] = byte;
            return;
        }


        // ====================================================
        // ЭТАП 2: Ищем второй байт заголовка (0x40)
        // ====================================================
        // Если это не 0x40, то предыдущий 0x20 был случайным
        // → Сбрасываем парсер и начинаем заново
        // ====================================================

        if (frameIndex == 1)
        {
            if (byte != Config::IBUS_HEADER_1)
            {
                frameIndex = 0;  // Ложная тревога, начинаем заново
                return;
            }

            frame[frameIndex++] = byte;
            return;
        }


        // ====================================================
        // ЭТАП 3: Накопление данных кадра
        // ====================================================
        // После заголовка идут 30 байт данных
        // (канальные значения + checksum)
        // ====================================================

        frame[frameIndex++] = byte;


        // ====================================================
        // ЭТАП 4: Полный кадр получен?
        // ====================================================
        // Если собрали 32 байта (2 заголовка + 30 данных)
        // → Обработать кадр и сбросить счётчик
        // ====================================================

        if (frameIndex >= Config::IBUS_FRAME_LENGTH)
        {
            processFrame();     // Парсим каналы и checksum
            frameIndex = 0;     // Сбрасываем для следующего кадра
        }
    }


    // ========================================================
    // ОБРАБОТКА ПОЛНОГО КАДРА
    // ========================================================
    // Вызывается когда собрали 32 байта iBUS кадра
    //
    // Алгоритм:
    //   1. Рассчитываем checksum (контрольная сумма)
    //   2. Сравниваем с переданным checksum
    //   3. Если совпадает:
    //      • Извлекаем 10 каналов (CH1-CH10)
    //      • Записываем время получения
    //   4. Если не совпадает:
    //      • Игнорируем кадр (помехи в эфире)
    //
    // Checksum:
    //   Сумма ВСЕХ первых 30 байт кадра
    //   Формула: CRC = 0xFFFF - (sum всех 30 байт)
    //   Передаётся в байтах 30-31 (little-endian)
    // ========================================================

    void processFrame()
    {
        // Рассчитываем checksum
        uint16_t checksum = 0xFFFF;

        // Первые 30 байт участвуют в checksum
        for (uint8_t i = 0; i < 30; ++i)
        {
            checksum -= frame[i];
        }


        // ====================================================
        // Checksum, переданный приёмником (байты 30-31)
        // ====================================================

        const uint16_t receivedChecksum =
            static_cast<uint16_t>(frame[30]) |
            (static_cast<uint16_t>(frame[31]) << 8);


        // ====================================================
        // ПРОВЕРКА: Checksum совпадает?
        // ====================================================
        // Если не совпадает → помехи/шум в эфире
        // → Игнорируем этот кадр и ждём следующего
        // ====================================================

        if (checksum != receivedChecksum)
        {
            return;  // Плохой кадр, игнорируем
        }


        // ====================================================
        // ИЗВЛЕЧЕНИЕ 10 КАНАЛОВ
        // ====================================================
        // Кадр содержит 10 каналов (CH1-CH10)
        // Каждый канал = 2 байта (little-endian)
        //
        // Расположение в кадре:
        //   Байты 0-1:   заголовок (0x20, 0x40)
        //   Байты 2-3:   CH1 (низкий байт, высокий байт)
        //   Байты 4-5:   CH2
        //   Байты 6-7:   CH3
        //   ...
        //   Байты 20-21: CH10
        //   Байты 22-31: зарезервировано
        // ====================================================

        for (uint8_t channel = 0;
             channel < Config::IBUS_CHANNELS;  // 10 каналов
             ++channel)
        {
            // Позиция в кадре (каждый канал = 2 байта)
            const uint8_t lowByte  = frame[2 + channel * 2];
            const uint8_t highByte = frame[3 + channel * 2];

            // Объединяем два байта в 16-bit число (little-endian)
            // Пример: если lowByte=0xDC, highByte=0x05
            //   → value = 0xDC | (0x05 << 8) = 0x05DC = 1500
            const uint16_t value =
                static_cast<uint16_t>(lowByte) |
                (static_cast<uint16_t>(highByte) << 8);

            // Сохраняем значение в RcChannelState объект
            state.set(channel, value);
        }


        // ====================================================
        // ФИКСИРУЕМ ВРЕМЯ ПОЛУЧЕНИЯ
        // ====================================================
        // Сохраняем micros() момента получения валидного кадра
        // Используется для проверки failsafe (potency loss)
        //
        // Если следующий валидный кадр придёт позже чем
        // через 500ms (Config::RX_TIMEOUT_US):
        //   → isSignalLost() вернёт true
        //   → FlightController запустит failsafe режим
        // ====================================================

        lastFrameTime = micros();
    }
};