#pragma once
#include <stddef.h>
#include <stdint.h>

// ============================================================
// Область флеша под журнал (чёрный ящик) — NOR-флеш как есть:
//   • стирание — только целыми секторами 4 КБ (адрес и длина кратны
//     4096), стёртое читается как 0xFF;
//   • запись только опускает биты 1 -> 0: писать можно в стёртые
//     байты, в том числе по частям в одну и ту же страницу;
//   • на ESP32 и стирание, и запись останавливают ОБА ядра (кэш
//     флеша выключен): запись страницы 256 байт — доли миллисекунды,
//     стирание сектора — десятки мс, блока 64 КБ — сотни. Поэтому
//     вызывающий сам решает, когда это можно (BlackBox стирает только
//     на земле без ARM).
//
// Реализация: Esp32FlashPartition (раздел в partitions_blackbox.csv).
// ============================================================

class IFlashRegion
{
public:
    virtual ~IFlashRegion() = default;

    // Размер области, байт (0 — области нет).
    virtual uint32_t size() const = 0;

    virtual bool read(uint32_t offset, void* data, size_t length) = 0;
    virtual bool write(uint32_t offset, const void* data, size_t length) = 0;
    virtual bool erase(uint32_t offset, uint32_t length) = 0;

    // Метка "кольцо пусто". Область, которая её умеет (SdFileRegion), хранит её
    // в служебном секторе вне кольца: при включении пустое кольцо опознаётся
    // одним чтением, а не проходом по всей области (на SD-карте — секунды).
    // BlackBoxStorage ставит метку, когда убедился, что полётов нет (стёрто всё /
    // полная сверка ничего не нашла), и снимает перед первой записью в кольцо.
    // По умолчанию области метки не умеют: метка не ставится и не читается.
    virtual bool ringMarkedEmpty() { return false; }
    virtual void markRingEmpty() {}
    virtual void clearRingMark() {}
};
