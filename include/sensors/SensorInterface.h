#pragma once

// ============================================================
// 🔌 ABSTRACT SENSOR INTERFACE
//
// Все датчики реализуют этот интерфейс.
// Это позволяет легко добавлять новые датчики без изменения
// остального кода (Dependency Inversion Principle).
//
// Актуальный список подключённых чипов и как его сменить — в
// sensors/SensorSelection.h. Здесь только сами интерфейсы
// категорий (IMU/барометр/магнитометр/GPS), не конкретные чипы.
// ============================================================

#include <Arduino.h>

// ============================================================
// СТРУКТУРЫ ДАННЫХ ДЛЯ СТАНДАРТИЗИРОВАННОГО ВЫВОДА
// ============================================================

// Данные IMU (Inertial Measurement Unit) — гироскоп + акселерометр
struct ImuData
{
    // Угловые скорости, °/с, авиационные знаки (см. ImuSensorBase.h)
    float gyroX;  // крен:     + правое крыло вниз
    float gyroY;  // тангаж:   + нос вверх
    float gyroZ;  // рысканье: + нос вправо

    // Ускорение, g, оси самолёта: X к носу, Y влево, Z вверх
    float accelX;
    float accelY;
    float accelZ;

    // Ориентация, °, те же знаки, что у угловых скоростей
    float roll;   // -180..+180
    float pitch;  // -90..+90
    float yaw;    // -180..+180, интеграл гироскопа (уплывает)

    // Температура (°C)
    float temperature;

    // Временная метка (микросекунды)
    uint32_t timestamp;
};

// Данные Barometer (барометр)
struct BarometerData
{
    // Давление (Па)
    float pressure;

    // Температура (°C)
    float temperature;

    // Высота над уровнем моря (метры)
    // Рассчитывается из давления
    float altitude;

    // Изменение высоты (м/сек)
    float verticalSpeed;

    // Временная метка
    uint32_t timestamp;
};

// ============================================================
// БАЗОВЫЙ КЛАСС ДЛЯ ВСЕХ ДАТЧИКОВ
// ============================================================

class Sensor
{
public:
    virtual ~Sensor() = default;

    // ========================================================
    // ИНИЦИАЛИЗАЦИЯ
    // ========================================================
    // Должна вернуть true если датчик успешно инициализирован
    virtual bool begin() = 0;

    // ========================================================
    // ПРОВЕРКА ДОСТУПНОСТИ
    // ========================================================
    // Вернёт true, если датчик подключен и работает
    virtual bool isAvailable() const = 0;

    // ========================================================
    // ОБНОВЛЕНИЕ ДАННЫХ
    // ========================================================
    // Должна вызваться регулярно из loop()
    // Читает данные из датчика
    virtual void update() = 0;

    // ========================================================
    // ТИП ДАТЧИКА (для логирования)
    // ========================================================
    virtual const char* getSensorType() const = 0;

    // ========================================================
    // ДИАГНОСТИКА
    // ========================================================
    virtual void printStatus() const = 0;
};

// ============================================================
// ИНТЕРФЕЙС ДЛЯ IMU ДАТЧИКОВ (Гироскоп + Акселерометр)
// ============================================================

class ImuSensor : public Sensor
{
public:
    virtual ~ImuSensor() = default;

    // ========================================================
    // ПОЛУЧИТЬ ДАННЫЕ IMU
    // ========================================================
    // Возвращает последние считанные данные
    virtual const ImuData& getImuData() const = 0;

    // ========================================================
    // КАЛИБРОВКА
    // ========================================================
    // Должна вызваться в начале полёта, когда самолёт неподвижен
    // Сохраняет нулевые значения гироскопа
    virtual void calibrate() = 0;

    // ========================================================
    // ЗАДАТЬ ОРИЕНТАЦИЮ (для коррекции)
    // ========================================================
    // Используется для сброса yaw на начало полёта
    virtual void setYaw(float yaw) = 0;
};

// ============================================================
// ИНТЕРФЕЙС ДЛЯ BAROMETER ДАТЧИКОВ
// ============================================================

class BarometerSensor : public Sensor
{
public:
    virtual ~BarometerSensor() = default;

    // ========================================================
    // ПОЛУЧИТЬ ДАННЫЕ БАРОМЕТРА
    // ========================================================
    virtual const BarometerData& getBarometerData() const = 0;

    // ========================================================
    // КАЛИБРОВКА ВЫСОТЫ
    // ========================================================
    // Задаёт текущую высоту как нулевую (начальную)
    // Вызывается при включении самолёта на земле
    virtual void calibrateAltitude() = 0;

    // ========================================================
    // ЗАДАТЬ НАЧАЛЬНОЕ ДАВЛЕНИЕ
    // ========================================================
    // Используется для точной калибровки
    virtual void setSeaLevelPressure(float pressure) = 0;
};

// ============================================================
// СТРУКТУРА ДАННЫХ ДЛЯ GPS
// ============================================================
struct GpsData
{
    double latitude;          // градусы, +N/-S
    double longitude;         // градусы, +E/-W
    float altitude;           // метры над уровнем моря (MSL)
    float groundSpeed;        // м/с
    float heading;            // градусы, 0..360 (курс по земле)
    uint8_t numSatellites;
    uint8_t fixType;          // 0=нет фикса, 2=2D, 3=3D
    float horizontalAccuracy; // метры, оценка точности по горизонтали
    float verticalAccuracy;   // метры, оценка точности по высоте

    // Временная метка (микросекунды)
    uint32_t timestamp;
};

// ============================================================
// СТРУКТУРА ДАННЫХ ДЛЯ МАГНИТОМЕТРА
// ============================================================
struct MagData
{
    // Поле, мкТл, после hard-iron калибровки, в осях самолёта (X к носу, Y влево)
    float magX, magY, magZ;

    // Курс из атана магнитного поля в плоскости XY, 0..360 град.
    // Без компенсации наклона (roll/pitch) — см. MagnetometerBase.h.
    float headingDegrees;

    // Временная метка (микросекунды)
    uint32_t timestamp;
};

// ============================================================
// ИНТЕРФЕЙС ДЛЯ GPS ДАТЧИКОВ
// ============================================================

class GpsSensor : public Sensor
{
public:
    virtual ~GpsSensor() = default;

    // Последние разобранные данные GPS.
    virtual const GpsData& getGpsData() const = 0;

    // true, если есть хотя бы 2D-фикс (fixType >= 2).
    virtual bool hasFix() const = 0;
};

// ============================================================
// ИНТЕРФЕЙС ДЛЯ МАГНИТОМЕТРОВ
// ============================================================

class MagnetometerSensor : public Sensor
{
public:
    virtual ~MagnetometerSensor() = default;

    // Последние считанные данные магнитометра.
    virtual const MagData& getMagData() const = 0;

    // Offset-калибровка (hard-iron): вращать датчик ~10-20 сек,
    // min/max по каждой оси даёт нулевое смещение. Полной
    // эллипсоидной (soft-iron) калибровки здесь намеренно нет.
    virtual void calibrate() = 0;
};
