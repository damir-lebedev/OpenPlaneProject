#pragma once

// ============================================================
// 🔌 ABSTRACT SENSOR INTERFACE
//
// Все датчики реализуют этот интерфейс.
// Это позволяет легко добавлять новые датчики без изменения
// остального кода (Dependency Inversion Principle).
//
// Поддерживаемые датчики:
//   • BME280 (барометр: высота, температура, давление)
//   • MPU6050 GY-521 (гироскоп + акселерометр)
//   • В будущем: ICM20689, LPS22HB, и другие
// ============================================================

#include <Arduino.h>

// ============================================================
// СТРУКТУРЫ ДАННЫХ ДЛЯ СТАНДАРТИЗИРОВАННОГО ВЫВОДА
// ============================================================

// Данные IMU (Inertial Measurement Unit) — гироскоп + акселерометр
struct ImuData
{
    // Гироскоп (угловая скорость в град/сек)
    float gyroX;  // Roll rate (крен)
    float gyroY;  // Pitch rate (тангаж)
    float gyroZ;  // Yaw rate (рысканье)

    // Акселерометр (ускорение в g)
    float accelX;
    float accelY;
    float accelZ;

    // Ориентация (углы в градусах)
    // Рассчитываются из акселерометра и гироскопа
    float roll;   // Крен (-180...+180 град)
    float pitch;  // Тангаж (-90...+90 град)
    float yaw;    // Рысканье (-180...+180 град)

    // Температура (°C)
    float temperature;

    // Временная метка (микросекунды)
    uint32_t timestamp;
};

// Данные Barometer (барометр)
struct BarometerData
{
    // Давление (Па)
    float pressure;

    // Температура (°C)
    float temperature;

    // Высота над уровнем моря (метры)
    // Рассчитывается из давления
    float altitude;

    // Изменение высоты (м/сек)
    float verticalSpeed;

    // Временная метка
    uint32_t timestamp;
};

// ============================================================
// БАЗОВЫЙ КЛАСС ДЛЯ ВСЕХ ДАТЧИКОВ
// ============================================================

class Sensor
{
public:
    virtual ~Sensor() = default;

    // ========================================================
    // ИНИЦИАЛИЗАЦИЯ
    // ========================================================
    // Должна вернуть true если датчик успешно инициализирован
    virtual bool begin() = 0;

    // ========================================================
    // ПРОВЕРКА ДОСТУПНОСТИ
    // ========================================================
    // Вернёт true, если датчик подключен и работает
    virtual bool isAvailable() const = 0;

    // ========================================================
    // ОБНОВЛЕНИЕ ДАННЫХ
    // ========================================================
    // Должна вызваться регулярно из loop()
    // Читает данные из датчика
    virtual void update() = 0;

    // ========================================================
    // ТИП ДАТЧИКА (для логирования)
    // ========================================================
    virtual const char* getSensorType() const = 0;

    // ========================================================
    // ДИАГНОСТИКА
    // ========================================================
    virtual void printStatus() const = 0;
};

// ============================================================
// ИНТЕРФЕЙС ДЛЯ IMU ДАТЧИКОВ (Гироскоп + Акселерометр)
// ============================================================

class ImuSensor : public Sensor
{
public:
    virtual ~ImuSensor() = default;

    // ========================================================
    // ПОЛУЧИТЬ ДАННЫЕ IMU
    // ========================================================
    // Возвращает последние считанные данные
    virtual const ImuData& getImuData() const = 0;

    // ========================================================
    // КАЛИБРОВКА
    // ========================================================
    // Должна вызваться в начале полёта, когда самолёт неподвижен
    // Сохраняет нулевые значения гироскопа
    virtual void calibrate() = 0;

    // ========================================================
    // ЗАДАТЬ ОРИЕНТАЦИЮ (для коррекции)
    // ========================================================
    // Используется для сброса yaw на начало полёта
    virtual void setYaw(float yaw) = 0;
};

// ============================================================
// ИНТЕРФЕЙС ДЛЯ BAROMETER ДАТЧИКОВ
// ============================================================

class BarometerSensor : public Sensor
{
public:
    virtual ~BarometerSensor() = default;

    // ========================================================
    // ПОЛУЧИТЬ ДАННЫЕ БАРОМЕТРА
    // ========================================================
    virtual const BarometerData& getBarometerData() const = 0;

    // ========================================================
    // КАЛИБРОВКА ВЫСОТЫ
    // ========================================================
    // Задаёт текущую высоту как нулевую (начальную)
    // Вызывается при включении самолёта на земле
    virtual void calibrateAltitude() = 0;

    // ========================================================
    // ЗАДАТЬ НАЧАЛЬНОЕ ДАВЛЕНИЕ
    // ========================================================
    // Используется для точной калибровки
    virtual void setSeaLevelPressure(float pressure) = 0;
};
